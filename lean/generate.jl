# Write the Lean 4 theorems that CI checks against Mathlib (.github/workflows/lean.yml):
#
#     julia --project=../docs generate.jl     (in lean/)
#
# The statements come from the relations of the examples; proofs are `norm_num` where it applies
# (rational solutions) and `sorry` elsewhere, so that every statement is at least type-checked.

using Equations

theorems = String[]

# The circle and the line of the examples, as a theorem with hypotheses.
push!(theorems, lean_theorem(Relation(:(x^2 + y^2 == 1));
    name="circle_from_line", hypotheses=[Relation(:(y == x / 2)), Relation(:(5 * x^2 == 4))]))

# A linear system and its solution, proved by norm_num.
linear = EquationSystem(Relation(:(x + y == 3)), Relation(:(x - y == 1)))
push!(theorems, lean_check(linear, (x=2, y=1); name="linear_solution"))

# The rectangle of the examples: area 12 and perimeter 14 for width 4 and height 3.
rectangle = EquationSystem(Relation(:(w * h == 12)), Relation(:(2w + 2h == 14)))
push!(theorems, lean_check(rectangle, (w=4, h=3); name="rectangle_solution"))

# Rational and decimal values.
push!(theorems, lean_check(Relation(:(3x - 1 == 1 / 2)), (x=1//2,); name="rational_solution"))
push!(theorems, lean_check(Relation(:(10x == 1.5)), (x=0.15,); name="decimal_solution"))

# An inequality that holds for the solution.
push!(theorems, lean_check(EquationSystem(Relation(:(x^2 + y^2 <= 25)), Relation(:(x > y))), (x=4, y=3);
    name="inequalities_hold"))

# The closed form of x² = 2 (the proof is left open: norm_num alone does not simplify √2 ^ 2).
push!(theorems, lean_check(Relation(:(x^2 == 2)), (x=:(sqrt(2)),); name="sqrt_two", proof="sorry"))

# Statements with transcendental functions and real exponents, type-checked only.
push!(theorems, lean_theorem(Relation(:(sin(t)^2 + cos(t)^2 == 1)); name="pythagorean_identity"))
push!(theorems, lean_theorem(Relation(:(exp(log(x)) == x)); name="exp_log", hypotheses=[Relation(:(x > 0))]))
push!(theorems, lean_theorem(Relation(:(x^(1//2) * x^(1//2) == x)); name="half_powers", hypotheses=[Relation(:(x >= 0))]))
push!(theorems, lean_theorem(Relation(:(abs(x - y) <= abs(x) + abs(y))); name="triangle_inequality"))
push!(theorems, lean_theorem(Relation(:(x^-1 * x == 1)); name="inverse", hypotheses=[Relation(:(x != 0))]))

path = joinpath(@__DIR__, "EquationsLean", "Generated.lean")
write(path, "-- Generated by lean/generate.jl from Equations.jl; do not edit.\n" * lean_file(theorems...))
println("wrote $(length(theorems)) theorems to $path")
